#!/usr/bin/env python3
"""Split a HolySic sound bank (.hsb, see build_bank.py) into downloadable pieces.

The app no longer ships the ~24 MB bank: it downloads only the instruments a song (or the user)
needs, and keeps them for later. Instruments share samples heavily (all 13 drum kits reuse the
Standard kit, piano variations reuse the grand…), so a pack per instrument would weigh ~115 MB in
total. Instead every sample belongs to exactly ONE pack — the first instrument (in bank order:
GM bank 0, the GS variations, then the drum kits) that uses it — and an instrument lists the packs
holding its samples. Downloading "Room kit" then fetches its own few samples plus the Standard
kit's pack; nothing is ever downloaded twice.

  python3 scripts/soundbank/split_bank.py holysic-gm.hsb public/soundbank/gu1 \
      src/services/audio/sf/instrumentManifest.ts

Outputs
  <out>/index.hsi   the bank without its sample pool (magic 'HSBI'; same layout as .hsb):
                    sample table, presets, regions, modulators — needed by every render
  <out>/<b>-<p>.hsp sample pack owned by preset bank b / program p:
                      'HSPK' u32 version=1, u32 count, u32 frames
                      count x { u32 sampleId, u32 blockFrames }
                      i16 blocks — each = 2 guard frames + the sample + 2 guard frames, exactly as
                      in the .hsb pool (so an assembled pool renders bit-identically)
  manifest .ts      sizes, pack list and per-preset dependencies, bundled with the app

The TypeScript (soundBank.ts › assembleBank) and C (HSSampleSynth.m › HSBankLoadParts) loaders
rebuild a normal in-memory bank from index + packs; samples whose pack is absent are marked
missing (offset 0xFFFFFFFF) and never sound.
"""
import json
import os
import struct
import sys

REGION_BYTES = 152
MOD_BYTES = 10


def main(src, out_dir, manifest_ts, version='gu1'):
    b = open(src, 'rb').read()
    magic, ver, ns, npre, nreg, nmod, pool_frames, sr = struct.unpack_from('<4s7I', b, 0)
    assert magic == b'HSBK' and ver == 1, 'not a v1 .hsb'
    o_samples = 32
    o_presets = o_samples + ns * 16
    o_regions = o_presets + npre * 36
    o_mods = o_regions + nreg * REGION_BYTES
    o_end = o_mods + nmod * MOD_BYTES
    o_pool = (o_end + 3) & ~3

    samples = [struct.unpack_from('<IIfI', b, o_samples + i * 16) for i in range(ns)]
    presets = []
    for i in range(npre):
        bank, prog, rs, rc = struct.unpack_from('<HHII', b, o_presets + i * 36)
        name = b[o_presets + i * 36 + 12:o_presets + i * 36 + 36].split(b'\0')[0].decode('latin1')
        sids = sorted({struct.unpack_from('<H', b, o_regions + r * REGION_BYTES + 4)[0]
                       for r in range(rs, rs + rc)})
        presets.append((bank, prog, name, sids))

    owner = {}
    for bank, prog, _, sids in presets:
        for s in sids:
            owner.setdefault(s, f'{bank}-{prog}')

    os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        if f.endswith('.hsp') or f == 'index.hsi':
            os.remove(os.path.join(out_dir, f))

    # index: everything but the pool
    index = bytearray(b[:o_end])
    index[0:4] = b'HSBI'
    struct.pack_into('<I', index, 24, 0)  # poolFrames
    open(os.path.join(out_dir, 'index.hsi'), 'wb').write(bytes(index))

    packs = {}
    by_pack = {}
    for s in range(ns):
        by_pack.setdefault(owner[s], []).append(s)
    for pid, sids in by_pack.items():
        head = bytearray(b'HSPK')
        blocks = []
        total = 0
        for s in sids:
            off, n, _, _ = samples[s]
            start = off - 2
            frames = n + 4
            blocks.append(b[o_pool + start * 2:o_pool + (start + frames) * 2])
            total += frames
        head += struct.pack('<3I', 1, len(sids), total)
        for s, blk in zip(sids, blocks):
            head += struct.pack('<II', s, len(blk) // 2)
        data = bytes(head) + b''.join(blocks)
        open(os.path.join(out_dir, f'{pid}.hsp'), 'wb').write(data)
        packs[pid] = len(data)

    deps = []
    for bank, prog, name, sids in presets:
        deps.append([bank, prog, name.strip(), sorted({owner[s] for s in sids},
                                                     key=lambda k: tuple(map(int, k.split('-'))))])

    total = sum(packs.values())
    lines = [
        '// GENERATED by scripts/soundbank/split_bank.py — do not edit by hand.',
        '// GeneralUser GS (S. Christian Collins), split into downloadable sample packs.',
        '/* eslint-disable */',
        'export interface InstrumentManifest {',
        '  version: string;',
        '  indexBytes: number;',
        '  /** pack id ("bank-program" of the owning preset) → bytes */',
        '  packs: Record<string, number>;',
        '  /** [bank, program, name, pack ids] in bank order (= preset index) */',
        '  presets: [number, number, string, string[]][];',
        '}',
        '',
        'export const INSTRUMENT_MANIFEST: InstrumentManifest = {',
        f'  version: {json.dumps(version)},',
        f'  indexBytes: {len(index)},',
        '  packs: ' + json.dumps(packs, separators=(',', ':')) + ',',
        '  presets: ' + json.dumps(deps, separators=(',', ':'), ensure_ascii=True) + ',',
        '};',
        '',
    ]
    open(manifest_ts, 'w').write('\n'.join(lines))
    print(f'index {len(index)/1e6:.2f} MB, {len(packs)} packs {total/1e6:.2f} MB '
          f'(largest {max(packs.values())/1e6:.2f} MB)', file=sys.stderr)


if __name__ == '__main__':
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    main(*sys.argv[1:4])
